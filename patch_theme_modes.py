#!/usr/bin/env python3
"""
patch_theme_modes.py — roll out Auto / Light / Dim / Dark site-wide.

What it does (idempotent; safe to re-run after adding pages):
  1. Runs build_theme_dim.py to regenerate assets/theme-dim.css.
  2. Writes fingerprinted copies assets/theme.<hash>.js and
     assets/theme-dim.<hash>.css (immutable-cached via _headers) and removes
     stale fingerprints.
  3. In every page that has dark-mode support, replaces the legacy pre-paint
     one-liner

       <script>try{if(localStorage.getItem('wgmr-dark')==='1')...}catch(e){}</script>

     with the theme bootstrap (pre-paint, zero CLS) plus a deferred
     <script src="/assets/theme.<hash>.js">. Pages without the one-liner but
     with dark-mode CSS get the block inserted right after <head>. Pages that
     already carry the block get it refreshed in place (new hashes).

The bootstrap must stay in <head>, before first paint. Never convert it to a
post-paint restore — see CLAUDE.md (theme modes).

Usage (repo root):
  python3 patch_theme_modes.py             # build + patch all pages
  python3 patch_theme_modes.py --dry-run   # report only
  python3 patch_theme_modes.py --page guides/igan-guide.html
"""

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent
ASSETS = REPO / "assets"
SKIP_DIRS = {".git", "node_modules", "tests", "scripts-qa", "blueprints", "docs"}

LEGACY = ("<script>try{if(localStorage.getItem('wgmr-dark')==='1')"
          "document.documentElement.setAttribute('data-theme','dark');}catch(e){}</script>")
BLOCK_RE = re.compile(r"<!-- rc-theme-boot -->.*?<!-- /rc-theme-boot -->\n?", re.S)
HAS_DARK = re.compile(r"\[data-theme=['\"]?dark|toggleDark")
HEAD_RE = re.compile(r"<head[^>]*>\n?", re.I)
# Legacy in-body dark restorers that run before #darkLabel exists and throw,
# aborting the rest of their <script> (e.g. the language restore). The head
# bootstrap now restores the theme, so these are removed.
LEGACY_RESTORE = re.compile(
    r"\(function\(\)\{(?:const|var|let) s=localStorage\.getItem\((?:DK|DARK_KEY|'wgmr-dark'|'wgmr-dk')\);"
    r"if\(s==='1'\)\{document\.documentElement\.setAttribute\('data-theme','dark'\);"
    r"document\.getElementById\('darkLabel'\)\.textContent='Light';\}\}\)\(\);\n?"
)

BOOT = """<!-- rc-theme-boot -->
<script>/* Theme bootstrap: Auto/Light/Dim/Dark/E-paper, applied BEFORE first paint (zero CLS). Generated by patch_theme_modes.py — see assets/theme.js. */
(function(){try{var d=document.documentElement,s=localStorage,C='__DIM__',P='__EPAPER__';window.__RC_DIM_CSS=C;window.__RC_EPAPER_CSS=P;
var m=s.getItem('wgmr-theme-mode');if(['auto','light','dim','dark','epaper'].indexOf(m)<0){m=s.getItem('wgmr-dark')==='1'?'dark':'auto';s.setItem('wgmr-theme-mode',m);}
var t=m;if(m==='auto'){var h=new Date().getHours();t=matchMedia('(prefers-color-scheme: dark)').matches?'dark':(h>=6&&h<18?'light':(h>=18&&h<22?'dim':'dark'));}
d.setAttribute('data-theme-mode',m);s.setItem('wgmr-dark',t==='dim'||t==='dark'?'1':'0');
if(t==='dim'||t==='dark')d.setAttribute('data-theme','dark');
d.setAttribute('data-dimg','__G__');if(t==='dim'){d.setAttribute('data-shade','dim');if(document.readyState==='loading'){document.write('<link id="rc-dim-css" rel="stylesheet" href="'+C+'">');}else{var l=document.createElement('link');l.id='rc-dim-css';l.rel='stylesheet';l.href=C;document.head.appendChild(l);}}
if(t==='epaper'){d.setAttribute('data-shade','epaper');if(document.readyState==='loading'){document.write('<link id="rc-epaper-css" rel="stylesheet" href="'+P+'">');}else{var q=document.createElement('link');q.id='rc-epaper-css';q.rel='stylesheet';q.href=P;document.head.appendChild(q);}}
}catch(e){}})();</script>
<script src="__JS__" defer></script>
<!-- /rc-theme-boot -->
"""


def fingerprint(src: Path, stem: str, ext: str) -> str:
    data = src.read_bytes()
    h = hashlib.sha256(data).hexdigest()[:10]
    dst = ASSETS / f"{stem}.{h}.{ext}"
    for old in ASSETS.glob(f"{stem}.*.{ext}"):
        if old != dst and re.fullmatch(rf"{re.escape(stem)}\.[0-9a-f]{{10}}\.{ext}", old.name):
            old.unlink()
    if not dst.exists():
        dst.write_bytes(data)
    return f"/assets/{dst.name}"


def iter_pages():
    for p in sorted(REPO.rglob("*.html")):
        rel = p.relative_to(REPO)
        if any(part in SKIP_DIRS for part in rel.parts):
            continue
        yield p


def patch(path: Path, block: str, dry: bool, groups: dict) -> str:
    html = path.read_text(encoding="utf-8")
    block = block.replace("__G__", groups.get(path.relative_to(REPO).as_posix(), ""))
    if BLOCK_RE.search(html):
        new = BLOCK_RE.sub(lambda _: block, html, count=1)
        new = new.replace(LEGACY, "")
        status = "refreshed"
    elif LEGACY in html:
        new = html.replace(LEGACY, block.rstrip("\n"), 1).replace(LEGACY, "")
        status = "replaced"
    elif HAS_DARK.search(html):
        m = HEAD_RE.search(html)
        if not m:
            return "no-head"
        new = html[:m.end()] + block + html[m.end():]
        status = "inserted"
    else:
        return "no-dark"
    new = LEGACY_RESTORE.sub("", new)
    if new == html:
        return "unchanged"
    if not dry:
        path.write_text(new, encoding="utf-8")
    return status


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--page")
    args = ap.parse_args()

    if not args.dry_run:
        subprocess.run([sys.executable, str(REPO / "build_theme_dim.py")], check=True)
    js = fingerprint(ASSETS / "theme.js", "theme", "js") if not args.dry_run else "/assets/theme.HASH.js"
    css = fingerprint(ASSETS / "theme-dim.css", "theme-dim", "css") if not args.dry_run else "/assets/theme-dim.HASH.css"
    ep = fingerprint(ASSETS / "theme-epaper.css", "theme-epaper", "css") if not args.dry_run else "/assets/theme-epaper.HASH.css"
    block = BOOT.replace("__DIM__", css).replace("__EPAPER__", ep).replace("__JS__", js)

    gpath = ASSETS / "theme-dim-groups.json"
    groups = json.loads(gpath.read_text(encoding="utf-8")) if gpath.exists() else {}
    pages = [REPO / args.page] if args.page else list(iter_pages())
    tally = {}
    for p in pages:
        st = patch(p, block, args.dry_run, groups)
        tally[st] = tally.get(st, 0) + 1
        if st == "no-head":
            print(f"  ! no <head>: {p.relative_to(REPO)}")
    print(("DRY RUN — " if args.dry_run else "") + ", ".join(f"{k}: {v}" for k, v in sorted(tally.items())))
    print(f"theme.js → {js}\ntheme-dim.css → {css}\ntheme-epaper.css → {ep}")


if __name__ == "__main__":
    main()
