# -*- coding: utf-8 -*-
"""Build quizbank.py for the Renal Transplant Coordinator track.

Bank per module = the 5 keyed items from the handoff curriculum.json (option-level rationales folded into one
explanation) + the 5 new application items in quiz_new.py (blueprint v2). Run from the repo root:

    python3 tools/techcourses/rtc/build_quizbank.py "<path to curriculum.json>"
"""
import html, importlib.util, json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def esc(s):
    s = html.escape(s, quote=False)
    return (s.replace("’", "&rsquo;").replace("‘", "&lsquo;").replace("“", "&ldquo;")
             .replace("”", "&rdquo;").replace("—", "&mdash;").replace("–", "&ndash;").replace("'", "&rsquo;"))


def main(src):
    cur = json.loads(Path(src).read_text(encoding="utf-8"))
    spec = importlib.util.spec_from_file_location("qn", HERE / "quiz_new.py"); qn = importlib.util.module_from_spec(spec); spec.loader.exec_module(qn)
    out = ['# -*- coding: utf-8 -*-',
           '"""Self-assessment banks for the Renal Transplant Coordinator track: 10 items per module.',
           'Items 1-5: the keyed handoff items (curriculum.json v1), option rationales folded into one explanation.',
           'Items 6-10: new application items (quiz_new.py, blueprint v2). Generated by build_quizbank.py; edit the sources, not this file."""',
           '', 'QUIZ = {']
    for m in cur["modules"]:
        mid = f'{m["number"]:02d}'
        items = []
        for q in m["questions"]:
            opts = [esc(o["text"]) for o in q["options"]]
            ans = [i for i, o in enumerate(q["options"]) if o["correct"]]
            assert len(ans) == 1, (mid, q["stem"])
            best = q["options"][ans[0]]
            why = "Best: " + esc(best["rationale"]) + " Why not the others: " + " ".join(
                f'&ldquo;{esc(o["text"])}&rdquo;: {esc(o["rationale"])}' for o in q["options"] if not o["correct"])
            items.append((esc(q["stem"]), opts, ans[0], why))
        items += [tuple(x) for x in qn.NEW[mid]]
        assert len(items) == 10, mid
        out.append(f'    "{mid}": [')
        for stem, opts, a, why in items:
            out.append(f'        ({stem!r},\n         {opts!r}, {a},\n         {why!r}),')
        out.append('    ],')
    out.append('}')
    (HERE / "quizbank.py").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote", HERE / "quizbank.py")


if __name__ == "__main__":
    main(sys.argv[1])
