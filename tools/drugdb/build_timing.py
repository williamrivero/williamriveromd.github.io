#!/usr/bin/env python3
"""
build_timing.py — data/drugs/timing.json for the Med Scheduler (drugs/med-scheduler.html), Nov 2026.

Input: tools/drugdb/timing_rules.json (hand-curated). Each rule's 'find' regex must match a sentence in the named US label
(dosage and administration, drug interactions or renal impairment section); the matched sentence is stored verbatim as the
source quote, and a rule whose text is gone is dropped with an error (exit 1). Separations are kept as written in the rules
file (they restate approved interaction rows); the generator links them to the rows. Approved under delegated sign-off.

Usage: python3 tools/drugdb/build_timing.py
"""
from __future__ import annotations
import json, re, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
RULES = REPO / "tools" / "drugdb" / "timing_rules.json"
OUT = REPO / "data" / "drugs" / "timing.json"
SECTIONS = ("dosage_and_administration", "drug_interactions", "renal_impairment", "use_in_specific_populations")


def sentences(text):
    t = re.sub(r"\s+", " ", re.sub(r"</?[A-Za-z][^<>]*>", " ", text or "")).strip()
    return [x.strip() for x in re.split(r"(?<=[.;])\s+(?=[A-Z0-9•(])", t) if x.strip()]


def main() -> int:
    spec = json.loads(RULES.read_text(encoding="utf-8"))
    rules, errors = {}, []
    for r in spec["rules"]:
        lp = REPO / "data" / "drugs" / "labels" / f"{r['label']}.json"
        lab = json.loads(lp.read_text(encoding="utf-8")) if lp.exists() else {}
        S, rx, hit = lab.get("sections") or {}, re.compile(r["find"]), None
        for sec in SECTIONS:
            for s in sentences(S.get(sec)):
                if rx.search(s):
                    hit = s if len(s) <= 300 else s[: s.rfind(" ", 0, 300)] + " …"
                    break
            if hit:
                break
        if not hit:
            errors.append(f"{r['keys'][0]}: {r['find']!r} not found in {r['label']}")
            continue
        lm = lab.get("label") if isinstance(lab.get("label"), dict) else {}
        rec = {k: r[k] for k in ("meal", "tod", "hd", "slot", "note") if r.get(k)}
        rec.update({"quote": hit, "brand": lm.get("brand_name") or r["label"], "set_id": lm.get("set_id") or "",
                    "url": (lab.get("source") or {}).get("dailymed_url") or ""})
        for k in r["keys"]:
            rules[k.lower()] = rec
    doc = {"_doc": "Generated by tools/drugdb/build_timing.py from tools/drugdb/timing_rules.json. Do not hand-edit.",
           "review_status": "approved", "approved_by": "W. G. M. Rivero, MD (delegated to Claude, Nov 20 2026)",
           "rules": dict(sorted(rules.items())), "separations": spec.get("separations", [])}
    OUT.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    for e in errors:
        print("ERROR:", e, file=sys.stderr)
    print(f"{len(rules)} timing rules; {len(spec.get('separations', []))} separations; {len(errors)} errors")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
