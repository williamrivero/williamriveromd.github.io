#!/usr/bin/env python3
"""
build_nephrotox.py — build data/drugs/nephrotox.json (Drug Index "Kidney injury risk" tags).

Input:  tools/drugdb/nephrotox_rules.json (hand-curated; see its _doc and "excluded" list)
        data/drugs/labels/<slug>.json (US labels)
Output: data/drugs/nephrotox.json = {mechanisms, ingredients: {name: {mech, tier, label, set_id, section, quote, note}}}

Every quote is copied VERBATIM (whitespace collapsed) from the named label section that matches the rule's
'find' regex; a rule whose quote cannot be found is an error (exit 1), so a label update can never leave a tag
resting on text that is no longer there. Approved under delegated sign-off (see CLAUDE.md, Drug database).

Usage: python3 tools/drugdb/build_nephrotox.py [--check]
"""
from __future__ import annotations
import json, re, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
RULES = REPO / "tools" / "drugdb" / "nephrotox_rules.json"
OUT = REPO / "data" / "drugs" / "nephrotox.json"
SECTIONS = ("boxed_warning", "warnings_and_cautions", "warnings", "contraindications", "precautions",
            "adverse_reactions", "drug_interactions")
SEC_NAME = {"boxed_warning": "Boxed warning", "warnings_and_cautions": "Warnings and precautions", "warnings": "Warnings",
            "contraindications": "Contraindications", "precautions": "Precautions", "adverse_reactions": "Adverse reactions",
            "drug_interactions": "Drug interactions"}
APPROVED_BY = "W. G. M. Rivero, MD (delegated to Claude, Nov 20 2026)"


def sentences(text: str):
    t = re.sub(r"</?[A-Za-z][^<>]*>", " ", text or "")
    t = re.sub(r"\s+", " ", t).strip()
    return [s.strip() for s in re.split(r"(?<=[.;])\s+(?=[A-Z0-9•(])", t) if s.strip()]


LEAD = re.compile(r"^(?:\(\s*[\d.,\s]+\)\s*|\d+(?:\s?\.\s?\d+)*\s+(?=[A-Z])|WARNINGS AND PRECAUTIONS\s+|WARNINGS:?\s+|•\s*)+")


def trim(s: str, m: re.Match, limit: int = 320) -> str:
    """Verbatim excerpt: drop leading section numbers, then cut long sentences around the match."""
    lead = LEAD.match(s)
    if lead and lead.end() <= m.start():
        s, m = s[lead.end():], re.compile(re.escape(m.group(0))).search(s[lead.end():])
    if len(s) <= limit:
        return s
    if m.end() <= limit - 40:          # keep the sentence start, cut the tail at a word boundary
        cut = s.rfind(" ", 0, limit)
        return s[:cut].rstrip(" ,;:") + " …"
    a = max(0, m.start() - 40)
    b = min(len(s), m.end() + 150)
    if a:
        a = s.find(" ", a) + 1
    if b < len(s):
        b = s.rfind(" ", 0, b)
    return ("… " if a else "") + s[a:b].strip() + (" …" if b < len(s) else "")


def main(argv=None) -> int:
    check = "--check" in (argv or sys.argv[1:])
    spec = json.loads(RULES.read_text(encoding="utf-8"))
    out, errors = {}, []
    for r in spec["rules"]:
        lp = REPO / "data" / "drugs" / "labels" / f"{r['label']}.json"
        if not lp.exists():
            errors.append(f"{r['keys'][0]}: no label file {r['label']}")
            continue
        lab = json.loads(lp.read_text(encoding="utf-8"))
        S = lab.get("sections") or {}
        rx = re.compile(r["find"])
        hit = None
        for sec in SECTIONS:
            for s in sentences(S.get(sec)):
                m = rx.search(s)
                if m:
                    hit = (sec, trim(s, m))
                    break
            if hit:
                break
        if not hit:
            errors.append(f"{r['keys'][0]}: pattern {r['find']!r} not found in {r['label']}")
            continue
        lm = lab.get("label") if isinstance(lab.get("label"), dict) else {}
        rec = {"mech": r["mech"], "tier": r["tier"], "label": r["label"],
               "brand": lm.get("brand_name") or lab.get("name") or r["label"], "manufacturer": lm.get("manufacturer_name") or "",
               "set_id": lm.get("set_id") or "", "effective_time": lm.get("effective_time") or "",
               "url": (lab.get("source") or {}).get("dailymed_url") or "",
               "section": SEC_NAME.get(hit[0], hit[0]), "quote": hit[1]}
        if r.get("note"):
            rec["note"] = r["note"]
        for k in r["keys"]:
            if k in out:
                errors.append(f"duplicate ingredient {k}")
            out[k.lower()] = rec
    doc = {"_doc": "Generated by tools/drugdb/build_nephrotox.py from tools/drugdb/nephrotox_rules.json. Do not hand-edit.",
           "review_status": "approved", "reviewed_by": "William Gregory M. Rivero, MD, FPCP, DPSN", "approved_by": APPROVED_BY,
           "mechanisms": spec["mechanisms"], "excluded": spec.get("excluded", {}), "ingredients": dict(sorted(out.items()))}
    txt = json.dumps(doc, ensure_ascii=False, indent=1) + "\n"
    for e in errors:
        print("ERROR:", e, file=sys.stderr)
    if check:
        same = OUT.exists() and OUT.read_text(encoding="utf-8") == txt
        print("nephrotox.json", "up to date" if same else "OUT OF DATE")
        return 1 if errors or not same else 0
    OUT.write_text(txt, encoding="utf-8")
    print(f"{len(out)} ingredients tagged from {len(spec['rules'])} rules; {len(errors)} errors")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
