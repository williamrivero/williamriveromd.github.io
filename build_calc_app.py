def ui_assets() -> dict:
    """Fingerprinted copies of assets/calc-ui.css/js (a new name per change, so no edge cache can serve stale)."""
    out = {}
    for ext, src in UI_SRC.items():
        raw = src.read_bytes()
        out[ext] = (f"/assets/calc-ui.{hashlib.sha1(raw).hexdigest()[:10]}.{ext}", raw)
    return out


