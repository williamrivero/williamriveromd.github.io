ASSET_RE = re.compile(r'''(?:src|href)=["']([^"'#]+?)(?:\?[^"']*)?["']''')


def assets_of(page: Path, t: str) -> set[str]:
    out = set()
    for ref in ASSET_RE.findall(t):
        if re.match(r"^(?:[a-z]+:|//|#|data:)", ref, re.I):
            if not ref.startswith("https://renalcarematters.com/"):
                continue
            ref = ref[len("https://renalcarematters.com"):]
        if not re.search(r"\.(js|css|png|jpe?g|webp|svg|ico|json|woff2?)$", ref, re.I):
            continue
        p = (REPO / ref.lstrip("/")) if ref.startswith("/") else (page.parent / ref)
        p = Path(os.path.normpath(p))
        if p.is_file() and REPO in p.parents:
            out.add("/" + p.relative_to(REPO).as_posix())
    return out


def offline_manifest(texts: dict[Path, str]) -> dict:
    files, assets = [], set()
    for p, t in texts.items():
        raw = t.encode("utf-8")
        files.append(["/guides/" + p.stem, hashlib.sha1(raw).hexdigest()[:10], len(raw)])
        assets |= assets_of(p, t)
    assets.add(f"/assets/calc-app.js")
    for a in sorted(assets):
        raw = (REPO / a.lstrip("/")).read_bytes()
        files.append([a, hashlib.sha1(raw).hexdigest()[:10], len(raw)])
    files.sort()
    h = hashlib.sha1(json.dumps(files, separators=(",", ":")).encode()).hexdigest()[:12]
    return {"v": 1, "h": h, "files": files}


def sizes_of(man: dict) -> dict:
    b = sum(f[2] for f in man["files"])
    n = sum(1 for f in man["files"] if f[0].startswith("/guides/calc-"))
    return {"n": n, "dl": max(5, int(round(b * 0.35 / 1e6 / 5.0)) * 5), "store": max(5, int(round(b / 1e6 / 5.0)) * 5)}


def build_sw() -> str:
    js = SW.replace("__AV__", ASSET_V)
    return js.replace("__V__", hashlib.sha1(js.encode()).hexdigest()[:10])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if any file would change (no writes)")
    a = ap.parse_args()
    changed = []

    def write(path: Path, content: str):
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != content:
            changed.append(path.relative_to(REPO).as_posix())
            if not a.check:
                path.write_text(content, encoding="utf-8")

    ui = ui_assets()
    for ext, (url, raw) in ui.items():
        dest = REPO / url.lstrip("/")
        if not dest.exists():
            changed.append(url.lstrip("/"))
            if not a.check:
                dest.write_bytes(raw)
        for old in (REPO / "assets").glob(f"calc-ui.*.{ext}"):
            if old != dest and not a.check:
                old.unlink()
    texts = {}
    for p in pages():
        t = patch_page(p.read_text(encoding="utf-8"))
        texts[p] = patch_ui(t, ui) if p.name.startswith("calc-") else t
    dri = G / "ckd-dri-calculator.html"   # a calculator outside the Calculo scope: design layer only
    if dri.exists():
        write(dri, patch_ui(dri.read_text(encoding="utf-8"), ui))
    idx = G / "calculators.html"
    # sizes are rounded, so a first pass is enough to fill the panel
    texts[idx] = patch_index(texts[idx], sizes_of(offline_manifest(texts)))
    for p, t in texts.items():
        write(p, t)
    write(G / "calc-app.webmanifest", json.dumps(MANIFEST, ensure_ascii=False, indent=1) + "\n")
    write(G / "calc-sw.js", build_sw())
    write(G / "calc-offline-manifest.json", json.dumps(offline_manifest(texts), separators=(",", ":")))
    print(f"Calculo: {len(texts)} pages · {len(changed)} file(s) {'would change' if a.check else 'changed'}")
    if a.check and changed:
        for c in changed[:20]:
            print("  ", c)
        sys.exit(1)


if __name__ == "__main__":
    main()
